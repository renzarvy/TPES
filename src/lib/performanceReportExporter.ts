  doc.text('Date Generated:', 18, 50);

  doc.setFont('helvetica', 'normal');
  doc.setTextColor(15, 23, 42);
  doc.text(`${academicYear} • ${semester}`, 45, 40);
  doc.text(selectedDepartment === 'all' ? 'All Academic Departments (Institutional Roster)' : selectedDepartment, 45, 45);
  doc.text(new Date().toLocaleDateString('en-US', { dateStyle: 'medium', timeStyle: 'short' }), 45, 50);

  doc.setFont('helvetica', 'bold');
  doc.setTextColor(71, 85, 105);
  doc.text('Authorized By:', pageWidth / 2 + 10, 40);
  doc.text('Faculty Evaluated:', pageWidth / 2 + 10, 45);
