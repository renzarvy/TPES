  const filteredReports = selectedDepartment === 'all' 
    ? reports 
    : reports.filter(r => r.department === selectedDepartment);

  const totalEvaluations = filteredReports.reduce((sum, r) => sum + (r.evaluationCount || 0), 0);
  const ratedFaculty = filteredReports.filter(r => r.evaluationCount > 0);
  const overallAvg = ratedFaculty.length > 0 
    ? (ratedFaculty.reduce((sum, r) => sum + r.averageScore, 0) / ratedFaculty.length).toFixed(2)
    : '0.00';
