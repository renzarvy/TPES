  doc.text(`${teacher.averageScore > 0 ? teacher.averageScore.toFixed(2) : '0.00'}`, 20, 81);
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text('/ 5.00 Maximum Rating', 46, 81);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(15, 23, 42);
